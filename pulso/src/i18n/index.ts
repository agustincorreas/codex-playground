const DICT = { es, en };

export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (key: TKey, vars?: Record<string, string | number>) => format(DICT[lang][key] ?? es[key], vars);
}

export function t(key: TKey, vars?: Record<string, string | number>) {
  const lang = useStore.getState().settings.lang;
  return format(DICT[lang][key] ?? es[key], vars);
}

function format(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
